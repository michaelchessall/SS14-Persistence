    private string[] _accessGroups = { "Faction", "Personal" };

    private bool _isMonotone;
    private string? _labelStyleClass;

    // Access data
    public HashSet<int> AccessAssignments = new();
    public HashSet<string> ActiveAccessAssignments = new();

    public Dictionary<int, string> AssignmentIdtoString = new();
    public HashSet<string> AccessNames = new();
