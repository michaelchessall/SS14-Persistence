namespace Content.Client.Access.UI;

[GenerateTypedNameReferences]
public sealed partial class GroupedAccessEntryChecklist : BoxContainer
{
    private static readonly string FactionAccesGroup = "Faction";
    private static readonly string PersonalAccessGroup = "Personal";

    private bool _isMonotone;
    private string? _labelStyleClass;

    // Access data
    private HashSet<int> _accessGroups = new(); //this variable and its set function arent really needed since 2 are practically hardcoded but il just leave it in case it could be expanded later to something more than just faction and personal
    public HashSet<int> _accessAssignments = new();
    public HashSet<string> _activeAccessAssignments = new();

    public Dictionary<int, string> _assignmentIdtoString = new();

    // Button groups
    private readonly ButtonGroup _accessGroupsButtons = new();

    // Temp values
    private int _accessGroupTabIndex = 0;
    private bool _canInteract = false;
    private List<string> _accessesForTab = new();

    private readonly List<AccessEntry> _accessEntries = new();
    private readonly Dictionary<string, List<string>> _groupedAccess = new();

    // Events
    public event Action<HashSet<int>, bool>? OnAccessAssignmentsChangedEvent;

    /// <summary>
    /// Creates a UI control for changing access entries.
    /// Access entries are organized under a list of tabs by their associated access group.
    /// </summary>
    public GroupedAccessEntryChecklist()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    private void ArrangeAccessControls()
    {
        // Create a list of known access groups with which to populate the UI
        _groupedAccess.Clear();

        _groupedAccess.Add(FactionAccesGroup, new());
        foreach (var accessAssignment in _accessAssignments)
        {
            //Console.WriteLine($"ui got {accessAssignment}");
            _groupedAccess[FactionAccesGroup].Add(accessAssignment.ToString());
        }

        // hiding personalAcces for now untill i get it working
        //_groupedAccess.Add(PersonalAccessGroup, new());

    }

    private bool TryRebuildAccessGroupControls()
    {
        AccessGroupList.RemoveAllChildren();
        AccessEntryChecklist.RemoveAllChildren();

        // No access entries were assigned to any of the access groups.
        // Either the turret controller has no assigned access entry or their names were invalid.
        if (_groupedAccess.Count == 0)
            return false;

        /*// Reorder the access groups alphabetically
        var orderedAccessGroups = _groupedAccess.Keys.OrderBy(x => x.GetAccessGroupName()).ToList();*/

        // Add group access buttons to the UI
        foreach (var accessGroup in _groupedAccess.Keys)
        {
            var accessGroupButton = CreateAccessGroupButton();

            // Button styling
            if (_groupedAccess.Count > 1)
            {
                if (AccessGroupList.ChildCount == 0)
                    accessGroupButton.AddStyleClass(StyleClass.ButtonOpenLeft);
                else if (_groupedAccess.Count > 1 && AccessGroupList.ChildCount == (_groupedAccess.Count - 1))
                    accessGroupButton.AddStyleClass(StyleClass.ButtonOpenRight);
                else
                    accessGroupButton.AddStyleClass(StyleClass.ButtonOpenBoth);
            }
            var tempComparestring = "";
            if (_accessGroupTabIndex == 0) tempComparestring = FactionAccesGroup;
            if (_accessGroupTabIndex == 1) tempComparestring = PersonalAccessGroup;
            accessGroupButton.Pressed = tempComparestring == accessGroup;

            // Label text and styling
            if (_labelStyleClass != null)
                accessGroupButton.Label.SetOnlyStyleClass(_labelStyleClass);

            var accessLevelPrototypes = _groupedAccess[accessGroup];
            var prefix = accessLevelPrototypes.All(x => _activeAccessAssignments.Contains(x))
                ? "»"
                : accessLevelPrototypes.Any(x => _activeAccessAssignments.Contains(x))
                    ? "›"
                    : " ";

            var text = Loc.GetString(
                "turret-controls-window-access-group-label",
                ("prefix", prefix),
                ("label", accessGroup.ToString())
            );

            accessGroupButton.Text = text;

            // Button events
            accessGroupButton.OnPressed += _ => OnAccessGroupChanged(accessGroupButton.GetPositionInParent());

            AccessGroupList.AddChild(accessGroupButton);
        }

        // Adjust the current tab index so it remains in range
        if (_accessGroupTabIndex >= _groupedAccess.Count)
            _accessGroupTabIndex = _groupedAccess.Count - 1;

        return true;
    }

    /// <summary>
    /// Rebuilds the checkbox list for the access entry controls.
    /// </summary>
    public void RebuildAccessEntriesControls()
    {
        AccessEntryChecklist.RemoveAllChildren();
        _accessEntries.Clear();

        // No access assignments were assigned to any of the access groups
        // Either turret controller has no assigned access entires, or their names were invalid
        if (_groupedAccess.Count == 0)
            return;

        // Reorder the access groups alphabetically
        var orderedAccessGroups = _groupedAccess.Keys.OrderBy(x => x.ToString()).ToList();

        // Get the access associated with the current tab
        var selectedAccessGroupTabProto = orderedAccessGroups[_accessGroupTabIndex];
        _accessesForTab = _groupedAccess[selectedAccessGroupTabProto];
        _accessesForTab = _accessesForTab.OrderBy(x => x.ToString()).ToList();

        // Add an 'all' checkbox as the first child of the list if it has more than one access
        // Toggling this checkbox on will mark all other boxes below it on/off
        var allCheckBox = CreateAccessEntryCheckbox();
        allCheckBox.Text = Loc.GetString("turret-controls-window-all-checkbox");

        if (_labelStyleClass != null)
            allCheckBox.Label.SetOnlyStyleClass(_labelStyleClass);

        // Add the 'all' checkbox events
        allCheckBox.OnPressed += args =>
        {
            SetCheckBoxPressedState(_accessEntries, allCheckBox.Pressed);

            var accessAssignments = new HashSet<int>();

            foreach (var accessAssignment in _accessAssignments)
            {
               accessAssignments.Add(accessAssignment);
            }
            OnAccessAssignmentsChangedEvent?.Invoke(accessAssignments, allCheckBox.Pressed);
        };
        AccessEntryChecklist.AddChild(allCheckBox);

        // Hide the 'all' checkbox if the tab has only one access entry
        var allCheckBoxVisible = _accessesForTab.Count > 1;

        allCheckBox.Visible = allCheckBoxVisible;
        allCheckBox.Disabled = !_canInteract;

        // Add any remaining missing access buttons to the UI
        foreach (var accessAssignment in _accessAssignments)
        {
            // Create the entry
            var accessEntry = new AccessEntry(_isMonotone);

            accessEntry.AccessAssignment = accessAssignment;
            accessEntry.CheckBox.Text = _assignmentIdtoString[accessAssignment];
            accessEntry.CheckBox.Pressed = _activeAccessAssignments.Contains(accessAssignment.ToString());
            accessEntry.CheckBox.Disabled = !_canInteract;

            if (_labelStyleClass != null)
                accessEntry.CheckBox.Label.SetOnlyStyleClass(_labelStyleClass);

            // Set the checkbox linkage lines
            var isEndOfList = _accessesForTab.IndexOf(accessAssignment.ToString()) == (_accessesForTab.Count - 1);

            var lines = new List<(Vector2, Vector2)>
            {
                (new Vector2(0.5f, 0f), new Vector2(0.5f, isEndOfList ? 0.5f : 1f)),
                (new Vector2(0.5f, 0.5f), new Vector2(1f, 0.5f)),
            };

            accessEntry.UpdateCheckBoxLink(lines);
            accessEntry.CheckBoxLink.Visible = allCheckBoxVisible;
            accessEntry.CheckBoxLink.Modulate = !_canInteract ? Color.Gray : Color.White;

            // Add checkbox events
            accessEntry.CheckBox.OnPressed += args =>
            {
                // If the checkbox and its siblings are checked, check the 'all' checkbox too
                allCheckBox.Pressed = AreAllCheckBoxesPressed(_accessEntries.Select(x => x.CheckBox));
                OnAccessAssignmentsChangedEvent?.Invoke([accessEntry.AccessAssignment], accessEntry.CheckBox.Pressed);
            };

            AccessEntryChecklist.AddChild(accessEntry);
            _accessEntries.Add(accessEntry);
        }

        // Press the 'all' checkbox if all others are pressed
        allCheckBox.Pressed = AreAllCheckBoxesPressed(_accessEntries.Select(x => x.CheckBox));
    }

    private bool AreAllCheckBoxesPressed(IEnumerable<CheckBox> checkBoxes)
    {
        foreach (var checkBox in checkBoxes)
        {
            if (!checkBox.Pressed)
                return false;
        }

        return true;
    }

    private void SetCheckBoxPressedState(List<AccessEntry> accessLevelEntries, bool pressed)
    {
        foreach (var accessEntry in accessLevelEntries)
        {
            accessEntry.CheckBox.Pressed = pressed;
        }
    }


    /// <summary>
    /// Provides the UI with a list of access groups using which list of tabs should be populated.
    /// </summary>
    public void SetAccessGroups(HashSet<int> accessGroups)
    {
        _accessGroups = accessGroups;

        ArrangeAccessControls();

        if (TryRebuildAccessGroupControls())
            RebuildAccessEntriesControls();
    }

    /// <summary>
    /// Provides the UI with a list of access entries with which it can populate the currently selected tab.
    /// </summary>
    public void SetAccessAssignments(HashSet<int> accessAssignments)
    {
        _accessAssignments = accessAssignments;
    }

    public void SetAccessAssignmentstoId(Dictionary<int, string> assignmentIdtoString)
    {
        _assignmentIdtoString = assignmentIdtoString;

        ArrangeAccessControls();

        if (TryRebuildAccessGroupControls())
            RebuildAccessEntriesControls();
    }

    /// <summary>
    /// Sets which access entry checkboxes should be marked on the UI.
    /// </summary>
    public void SetActiveAccessAssignments(HashSet<string> activeAccessAssignments)
    {
        _activeAccessAssignments = activeAccessAssignments;

        if (TryRebuildAccessGroupControls())
            RebuildAccessEntriesControls();
    }

    /// <summary>
    /// Sets whether the local player can interact with the checkboxes.
    /// </summary>
    public void SetLocalPlayerAccessibility(bool canInteract)
    {
        _canInteract = canInteract;

        if (TryRebuildAccessGroupControls())
            RebuildAccessEntriesControls();
    }

    /// <summary>
    /// Sets whether the UI should use monotone buttons and checkboxes.
    /// </summary>
    public void SetMonotone(bool monotone)
    {
        _isMonotone = monotone;

        if (TryRebuildAccessGroupControls())
            RebuildAccessEntriesControls();
    }

    /// <summary>
    /// Applies the specified style to the labels on the UI buttons and checkboxes.
    /// </summary>
    public void SetLabelStyleClass(string? styleClass)
    {
        _labelStyleClass = styleClass;

        if (TryRebuildAccessGroupControls())
            RebuildAccessEntriesControls();
    }

    private void OnAccessGroupChanged(int newTabIndex)
    {
        if (newTabIndex == _accessGroupTabIndex)
            return;

        _accessGroupTabIndex = newTabIndex;

        if (TryRebuildAccessGroupControls())
            RebuildAccessEntriesControls();
    }

    private Button CreateAccessGroupButton()
    {
        var button = _isMonotone ? new MonotoneButton() : new Button();

        button.ToggleMode = true;
        button.Group = _accessGroupsButtons;
        button.Label.HorizontalAlignment = HAlignment.Left;

        return button;
    }

    private CheckBox CreateAccessEntryCheckbox()
    {
        var checkbox = _isMonotone ? new MonotoneCheckBox() : new CheckBox();

        checkbox.Margin = new Thickness(0, 0, 0, 3);
        checkbox.ToggleMode = true;
        checkbox.ReservesSpace = false;

        return checkbox;
    }

    private sealed class AccessEntry : BoxContainer
    {
        public int AccessLevel;
        public int AccessAssignment;
        public readonly CheckBox CheckBox;
        public readonly LineRenderer CheckBoxLink;

        public AccessEntry(bool monotone)
        {
            HorizontalExpand = true;

            CheckBoxLink = new LineRenderer
            {
                SetWidth = 22,
                VerticalExpand = true,
                Margin = new Thickness(0, -1),
                ReservesSpace = false,
            };

            AddChild(CheckBoxLink);

            CheckBox = monotone ? new MonotoneCheckBox() : new CheckBox();
            CheckBox.ToggleMode = true;
            CheckBox.Margin = new Thickness(0f, 0f, 0f, 3f);

            AddChild(CheckBox);
        }

        public void UpdateCheckBoxLink(List<(Vector2, Vector2)> lines)
        {
            CheckBoxLink.Lines = lines;
        }
    }

    private sealed class LineRenderer : Control
    {
        /// <summary>
        /// List of lines to render (their start and end x-y coordinates).
        /// Position (0,0) is the top left corner of the control and
        /// position (1,1) is the bottom right corner.
        /// </summary>
        /// <remarks>
        /// The color of the lines is inherited from the control.
        /// </remarks>
        public List<(Vector2, Vector2)> Lines;

        public LineRenderer()
        {
            Lines = new List<(Vector2, Vector2)>();
        }

        public LineRenderer(List<(Vector2, Vector2)> lines)
        {
            Lines = lines;
        }

        protected override void Draw(DrawingHandleScreen handle)
        {
            foreach (var line in Lines)
            {
                var start = PixelPosition +
                            new Vector2(PixelWidth * line.Item1.X, PixelHeight * line.Item1.Y);

                var end = PixelPosition +
                          new Vector2(PixelWidth * line.Item2.X, PixelHeight * line.Item2.Y);

                handle.DrawLine(start, end, ActualModulateSelf);
            }
        }
    }
}
