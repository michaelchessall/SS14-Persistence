using Content.Shared.MessageBoard.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using System.Linq;

namespace Content.Client.MessageBoard.UI;
[GenerateTypedNameReferences]
public sealed partial class CreateEntry : DefaultWindow
{
    [Dependency] private IPrototypeManager _protoManager = default!;
    public enum EntryType : byte
    {
        Public,
        Direct
    }

    public EntryType CurrentEntryType = EntryType.Public;

    public CreateEntry()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        var cats = _protoManager.EnumeratePrototypes<MessageBoardCategoryPrototype>().OrderBy(p => p.Order).ThenBy(p => p.Name).ToList();
        int index = 0;
        foreach(var cat in cats)
        {
            CategoryButton.AddItem(cat.Name, index);
            CategoryButton.SetItemMetadata(index, cat);
            index++;
        }
        CategoryButton.SelectId(0);
        CategoryButton.OnItemSelected += args =>
        {
            CategoryButton.SelectId(args.Id);
        };
    }
}

