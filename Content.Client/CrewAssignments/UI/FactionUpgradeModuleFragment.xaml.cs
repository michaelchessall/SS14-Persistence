namespace Content.Client.CrewAssignments.UI;


[GenerateTypedNameReferences]
public sealed partial class FactionUpgradeModuleFragment : BoxContainer
{
    [Dependency] private readonly IPrototypeManager _prototypeManager = default!;

    public FactionUpgradeModuleFragment(KeyValuePair<ProtoId<UpgradeModuleTypePrototype>, int> kv, int progress)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        var upgradeProto = _prototypeManager.Index(kv.Key);
        var requiredNum = kv.Value;
        RequirementText.Text = $"{progress}/{requiredNum} {upgradeProto.Name} Upgrade Module";
        if(progress >= requiredNum)
        {
            ApplyButton.Pressed = true;
        }
    }
}
