using Content.Client.Stylesheets;
using Content.Shared._Persistence14.Codex.Prototypes;
using Content.Shared._Persistence14.Rumors.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Map;
using Robust.Shared.Prototypes;

namespace Content.Client.CrewAssignments.UI;


[GenerateTypedNameReferences]
public sealed partial class CodexPageFragment : BoxContainer
{
    [Dependency] private readonly IPrototypeManager _prototypeManager = default!;

    private JobNetMenu _owner;
    public CodexPageFragment(JobNetMenu jobNetMenu)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _owner = jobNetMenu;
    }

    public void UpdateState(ProtoId<CodexCategoryPrototype> codexCat, List<ProtoId<CodexEntryPrototype>> entryList, List<ProtoId<CodexEntryPrototype>> codexEntries)
    {
        RemoveAllChildren();
        foreach (var entry in entryList)
        {
            var entryProto = _prototypeManager.Index(entry);
            Button button = new();
            button.HorizontalExpand = true;
            button.Text = entryProto.Name;
            if(codexEntries.Contains(entry))
            {
                button.Disabled = false;
                button.OnPressed += _ => OnCodexOpen(entryProto);
            }
            else
            {
                button.Disabled = true;
                if(entryProto.UnlockHint != "")
                {
                    button.ToolTip = entryProto.UnlockHint;
                }
            }
            AddChild(button);
        }
    }

    private void OnCodexOpen(CodexEntryPrototype entry)
    {
        if (_owner.Owner == null || _owner.Owner.CodexMenu == null) return;
        _owner.Owner.CodexMenu.UpdateState(entry.Name, entry.Content);
        _owner.Owner.CodexMenu.OpenCentered();
    }
}
